// Package fixture builds the synthetic warehouse that every test in this
// repository runs against, and that scripts/setup-sample-data.sh installs for
// anyone who wants sample data to click around in.
//
// # Why the fixture is generated rather than downloaded
//
// The suites here used to bind to a slice of a third-party e-commerce dataset,
// redistributed in the repository. No licence for it could be established, so
// it could not be shipped — and with it would have gone the provider
// conformance suite, whose eight ground-truth figures were computed against
// that file.
//
// The data is now ours: generated by internal/fixture/gen, committed as CSV,
// licensed with the repository. That closes the legal question, and it buys
// something the borrowed dataset never offered — the properties the checks
// depend on are *guaranteed* rather than observed. See gen's package comment
// for the list.
//
// # Why CSV and not a committed .duckdb
//
// A DuckDB file is an opaque binary that a reviewer cannot read and git cannot
// diff, and the smallest possible one is still larger than this entire fixture.
// CSV means the ground truth in this package can be checked by eye against the
// rows it was derived from, and a change to the data shows up in review as a
// change to the data.
package fixture

import (
	"database/sql"
	"embed"
	"fmt"
	"os"
	"path/filepath"

	_ "github.com/marcboeker/go-duckdb/v2" // registers the "duckdb" driver
)

//go:embed testdata/*.csv
var files embed.FS

// Name is the filename Build and the setup script give the warehouse.
const Name = "analyst-sample.duckdb"

// Build materialises the embedded fixture as a DuckDB database inside dir and
// returns its path. dir must exist; the caller owns its lifetime (tests pass
// t.TempDir()).
func Build(dir string) (string, error) {
	csvDir := filepath.Join(dir, "csv")
	if err := os.MkdirAll(csvDir, 0o755); err != nil {
		return "", fmt.Errorf("fixture: mkdir %s: %w", csvDir, err)
	}
	entries, err := files.ReadDir("testdata")
	if err != nil {
		return "", fmt.Errorf("fixture: read embedded testdata: %w", err)
	}
	for _, e := range entries {
		b, err := files.ReadFile("testdata/" + e.Name())
		if err != nil {
			return "", fmt.Errorf("fixture: read embedded %s: %w", e.Name(), err)
		}
		if err := os.WriteFile(filepath.Join(csvDir, e.Name()), b, 0o644); err != nil {
			return "", fmt.Errorf("fixture: write %s: %w", e.Name(), err)
		}
	}
	out := filepath.Join(dir, Name)
	if err := Load(csvDir, out); err != nil {
		return "", err
	}
	return out, nil
}

// Load creates a DuckDB database at out and loads every table from the CSVs in
// csvDir. It is the one place the schema is applied, so the committed fixture
// and a freshly generated demo-scale dataset cannot end up with different
// column types.
//
// This opens DuckDB directly rather than through warehouse.OpenDuckDB, and that
// is deliberate: the product's connector opens read-only *and* disables every
// filesystem, so it can neither create this file nor read the CSVs. The
// lockdown exists to keep model-authored SQL away from the host; a build step
// running our own SQL over our own files is on the other side of that boundary.
func Load(csvDir, out string) error {
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return fmt.Errorf("fixture: mkdir for %s: %w", out, err)
	}
	// A stale file would be appended to, not replaced, and the row counts would
	// silently double.
	if err := os.Remove(out); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("fixture: remove existing %s: %w", out, err)
	}

	db, err := sql.Open("duckdb", out)
	if err != nil {
		return fmt.Errorf("fixture: open %s: %w", out, err)
	}
	defer db.Close()

	if _, err := db.Exec(schema); err != nil {
		return fmt.Errorf("fixture: apply schema: %w", err)
	}
	for _, t := range tables {
		src := filepath.Join(csvDir, t+".csv")
		if _, err := os.Stat(src); err != nil {
			return fmt.Errorf("fixture: %s.csv missing from %s: %w", t, csvDir, err)
		}
		// Column types come from the table, not the sniffer. HEADER skips the
		// name row; an empty field becomes NULL, which is how the nullable
		// lifecycle timestamps and events.user_id arrive.
		stmt := fmt.Sprintf("COPY %s FROM '%s' (FORMAT CSV, HEADER TRUE)", t, escapeSQL(src))
		if _, err := db.Exec(stmt); err != nil {
			return fmt.Errorf("fixture: load %s: %w", t, err)
		}
	}
	return nil
}

// escapeSQL quotes a path for a single-quoted SQL literal. Paths here come from
// our own code or a -out flag, not from a request, but a temp directory with an
// apostrophe in it should produce a file, not a syntax error.
func escapeSQL(s string) string {
	out := make([]byte, 0, len(s))
	for i := 0; i < len(s); i++ {
		if s[i] == '\'' {
			out = append(out, '\'')
		}
		out = append(out, s[i])
	}
	return string(out)
}
