// Package conformance scores a model provider against the job this product
// actually asks of it.
//
// Why this exists at all: a provider here does not merely "answer questions".
// It writes the SQL that gets executed, and it writes the SECOND, independent
// derivation whose disagreement with the first is what produces the `contested`
// seal. So a provider that is slightly worse at SQL does not look worse — it
// produces more false `contested` results, and occasionally two equally wrong
// derivations that agree, which renders as **verified**. That failure is
// invisible in the UI and fatal to the product's only claim.
//
// A contribution whose quality cannot be measured therefore cannot be safely
// accepted. This suite makes the number visible. It deliberately does NOT gate
// on a threshold: "which model is good enough for verified answers?" is exactly
// the question a user of an open-source verification tool needs answered, and a
// hidden pass/fail hides it.
package conformance

