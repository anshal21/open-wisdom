// Options configure a run.
type Options struct {
	// Warehouse overrides the sample warehouse path.
	Warehouse string
	// Only restricts the run to named cases (substring match). Empty runs all.
	Only string
}

// WarehousePath resolves the warehouse to score against.
//
// The default builds the generated fixture, so the suite is runnable
// immediately after `git clone` with nothing fetched and nothing configured.
// That is the whole point: a conformance score an outsider cannot reproduce is
// a marketing number.
//
// The overrides exist for scoring a provider against your own data. The truths
// in Cases() are derived from the fixture, so pointing this elsewhere makes the
// correctness assertions meaningless — the shape, executability and
// independence assertions still hold, and those are most of the suite.
func WarehousePath(o Options) (string, error) {
	if o.Warehouse != "" {
		return o.Warehouse, nil
	}
	if p := os.Getenv("ANALYST_CONFORMANCE_WAREHOUSE"); p != "" {
		return p, nil
	}
	return fixture.Cached()
}

// Run scores a provider and returns the report. It never returns an error for a
// provider fault — those are assertions. It reports Setup for environment
// faults, which are not the provider's doing.
func Run(ctx context.Context, p llm.Provider, o Options) *Report {
	rep := &Report{Provider: p.Name()}
	start := time.Now()
	defer func() { rep.Elapsed = time.Since(start) }()

	prompts, err := LoadPrompts()
	if err != nil {
		rep.Setup = err
		return rep
	}

	path, err := WarehousePath(o)
	if err != nil {
		rep.Setup = fmt.Errorf("resolve conformance warehouse: %w", err)
		return rep
	}
	conn, err := warehouse.OpenDuckDB(path)
	if err != nil {
		rep.Setup = fmt.Errorf("open conformance warehouse %s: %w", path, err)
		return rep
	}
	defer conn.Close()

	// The ground-truth figures are timezone-dependent because created_at is
	// TIMESTAMP WITH TIME ZONE. Assert the environment matches how they were
	// computed, so a misconfiguration is diagnosed here instead of being
	// reported as eight provider failures.
	if err := assertUTC(ctx, conn); err != nil {
		rep.Setup = err
		return rep
	}

	cat, err := conn.Introspect(ctx)
	if err != nil {
		rep.Setup = fmt.Errorf("introspect: %w", err)
		return rep
	}
	if err := warehouse.NewProfiler(conn).Profile(ctx, cat); err != nil {
		rep.Setup = fmt.Errorf("profile: %w", err)
		return rep
	}
	digest := sources.Digest(cat)

	for _, c := range Cases() {
		if o.Only != "" && !strings.Contains(c.Name, o.Only) {
			continue
		}
		runCase(ctx, p, prompts, digest, conn, c, rep)
	}
	return rep
}

func assertUTC(ctx context.Context, conn warehouse.Connector) error {
	res, err := conn.Query(ctx, "SELECT current_setting('TimeZone') AS tz")
	if err != nil {
		return fmt.Errorf("read session timezone: %w", err)
	}
	tz, _ := res.Scalar()
	if s := fmt.Sprint(tz); s != "UTC" {
		return fmt.Errorf(
			"session timezone is %q, not UTC; the ground-truth figures were computed under UTC "+
				"and created_at is TIMESTAMP WITH TIME ZONE, so scoring here would be meaningless", s)
	}
	return nil
}

// call issues one model request and accumulates accounting.
func call(ctx context.Context, p llm.Provider, rep *Report, system, prompt string) (string, error) {
	res, err := p.Complete(ctx, llm.Request{
		System: system,
		Prompt: prompt,
		Speed:  llm.SpeedBalanced,
		JSON:   true,
	})
	rep.Calls++
	if err != nil {
		return "", err
	}
	rep.CostUSD += res.CostUSD
	return res.Text, nil
}

func runCase(
	ctx context.Context,
	p llm.Provider,
	prompts *Prompts,
	digest string,
	conn warehouse.Connector,
	c Case,
	rep *Report,
) {
	// Mirrors ask.buildPrompt: question, then the profiled schema. Context and
	// ratified definitions are omitted because a conformance run has neither.
	prompt := "QUESTION: " + c.Question + "\n\nSCHEMA AND MEASURED PROFILES:\n\n" + digest

	// ---- plan ----------------------------------------------------------
	var plan planReply
	planText, err := call(ctx, p, rep, prompts.Plan, prompt)
	if err != nil {
		rep.add(c, CatStructured, "plan call", false, err.Error())
		return
	}
	if err := llm.DecodeJSON(planText, &plan); err != nil {
		rep.add(c, CatStructured, "plan JSON", false, err.Error())
		return
	}
	rep.add(c, CatStructured, "plan JSON", true, "")
	rep.add(c, CatStructured, "plan has sql and restated", plan.SQL != "" && plan.Restated != "",
		fmt.Sprintf("sql=%q restated=%q", trunc(plan.SQL), trunc(plan.Restated)))

	primary, perr := conn.Query(ctx, plan.SQL)
	rep.add(c, CatExecutable, "plan SQL executes", perr == nil, detailOf(perr, plan.SQL))

	if c.Truth != nil {
		checkTruth(rep, c, "plan", plan.SQL, primary, perr)
	}

	// ---- alternates ----------------------------------------------------
	altText, err := call(ctx, p, rep, prompts.Alternates, prompt)
	if err != nil {
		rep.add(c, CatStructured, "alternates call", false, err.Error())
	} else {
		var alt altReply
		derr := llm.DecodeJSON(altText, &alt)
		rep.add(c, CatStructured, "alternates JSON", derr == nil, detailOf(derr, trunc(altText)))
		if derr == nil {
			// The prompt caps this at two. More than two is a provider
			// ignoring an explicit hard limit, which matters: each extra
			// reading is a query the pipeline executes before it can decide
			// whether to interrupt the user.
			rep.add(c, CatStructured, "alternates within limit", len(alt.Readings) <= 2,
				fmt.Sprintf("%d readings, prompt allows at most 2", len(alt.Readings)))
		}
	}

	// ---- cross-derivation ----------------------------------------------
	crossText, err := call(ctx, p, rep, prompts.Cross, prompt)
	if err != nil {
		rep.add(c, CatStructured, "cross call", false, err.Error())
		return
	}
	var cross crossReply
	if err := llm.DecodeJSON(crossText, &cross); err != nil {
		rep.add(c, CatStructured, "cross JSON", false, err.Error())
		return
	}
	rep.add(c, CatStructured, "cross JSON", true, "")

	altRes, aerr := conn.Query(ctx, cross.SQL)
	rep.add(c, CatExecutable, "cross SQL executes", aerr == nil, detailOf(aerr, cross.SQL))

	// The load-bearing independence assertion.
	diff := materiallyDifferent(plan.SQL, cross.SQL)
	rep.add(c, CatIndependent, "cross derivation is not a copy", diff,
		"the independent derivation is the primary query after cosmetic changes only; "+
			"agreement between a query and itself is not evidence")
	rep.Divergence = append(rep.Divergence, divergence(c.Name, plan.SQL, cross.SQL))

	if c.Truth != nil {
		checkTruth(rep, c, "cross", cross.SQL, altRes, aerr)
	}

	// ---- present -------------------------------------------------------
	if perr != nil {
		return // nothing to present
	}
	pres := presentPrompt(c.Question, plan, primary)
	presText, err := call(ctx, p, rep, prompts.Present, pres)
	if err != nil {
		rep.add(c, CatStructured, "present call", false, err.Error())
		return
	}
	var reply presentReply
	if err := llm.DecodeJSON(presText, &reply); err != nil {
		rep.add(c, CatStructured, "present JSON", false, err.Error())
		return
	}
	rep.add(c, CatStructured, "present JSON", true, "")
	rep.add(c, CatStructured, "present narrative non-empty",
		strings.TrimSpace(reply.Markdown) != "", "the presenter returned no sentence")
	rep.add(c, CatStructured, "chart type is valid",
		validChartTypes[reply.Chart.Type],
		fmt.Sprintf("type=%q is not one of line|bar|area|pie|scatter|table|scalar", reply.Chart.Type))

	// A chart naming a column that is not in the result renders as an empty
	// plot. The deterministic layer downstream discards the hint, so the user
	// sees a chart that silently ignored the model — worth catching here.
	rep.add(c, CatStructured, "chart references real columns",
		chartColumnsExist(reply.Chart, primary),
		fmt.Sprintf("chart x=%q y=%v not among result columns %v",
			reply.Chart.X, reply.Chart.Y, columnNames(primary)))
}

// presentPrompt mirrors the shape built by ask.Pipeline.present (pipeline.go
// :465-478). It is replicated rather than parsed because it is assembled by
// code, not declared as a constant.
func presentPrompt(question string, plan planReply, res *warehouse.Result) string {
	var b strings.Builder
	fmt.Fprintf(&b, "QUESTION: %s\n", question)
	fmt.Fprintf(&b, "INTERPRETED AS: %s\n", plan.Restated)
	if v, ok := res.Scalar(); ok {
		fmt.Fprintf(&b, "RESULT: %v (%s)\n", v, plan.Unit)
	} else {
		fmt.Fprintf(&b, "RESULT: a table of %d rows with columns %s\n",
			len(res.Rows), strings.Join(columnNames(res), ", "))
	}
	for _, a := range plan.Assumptions {
		fmt.Fprintf(&b, "ASSUMED: %s\n", a)
	}
	return b.String()
}

func columnNames(res *warehouse.Result) []string {
	if res == nil {
		return nil
	}
	out := make([]string, 0, len(res.Columns))
	for _, c := range res.Columns {
		out = append(out, c.Name)
	}
	return out
}

func chartColumnsExist(h chartHint, res *warehouse.Result) bool {
	have := map[string]bool{}
	for _, n := range columnNames(res) {
		have[strings.ToLower(n)] = true
	}
	named := append([]string{}, h.Y...)
	if h.X != "" {
		named = append(named, h.X)
	}
	if h.Series != "" {
		named = append(named, h.Series)
	}
	for _, n := range named {
		if n != "" && !have[strings.ToLower(n)] {
			return false
		}
	}
	return true
}

// checkTruth grades a derivation against the frozen figure.
//
// `sql` is the query the PROVIDER wrote, and printing it is the whole point of
// the failure detail. This once printed c.Truth.Query — the canonical query the
// figure was derived from — which reads as though the provider ran that exact
// SQL and got a different number, an impossibility that sends the reader
// hunting for a corrupt fixture. What a reviewer needs is the query that
// actually disagreed.
func checkTruth(rep *Report, c Case, which, sql string, res *warehouse.Result, qerr error) {
	name := which + " matches known value"
	if qerr != nil {
		rep.add(c, CatGroundTruth, name, false, "query failed: "+qerr.Error())
		return
	}
	v, ok := res.Scalar()
	if !ok {
		rep.add(c, CatGroundTruth, name, false,
			fmt.Sprintf("expected a single figure, got %d rows × %d columns",
				len(res.Rows), len(res.Columns)))
		return
	}
	got, ok := toFloat(v)
	if !ok {
		rep.add(c, CatGroundTruth, name, false, fmt.Sprintf("non-numeric result %v (%T)", v, v))
		return
	}
	want := c.Truth.Value
	delta := math.Abs(got - want)
	tol := c.Truth.Tolerance * math.Max(math.Abs(want), 1)
	rep.add(c, CatGroundTruth, name, delta <= tol,
		fmt.Sprintf("got %v, want %v\n    provider SQL: %s\n    truth derived by: %s",
			got, want, trunc(sql), c.Truth.Query))
}

func toFloat(v any) (float64, bool) {
	switch t := v.(type) {
	case float64:
		return t, true
	case float32:
		return float64(t), true
	case int64:
		return float64(t), true
	case int32:
		return float64(t), true
	case int:
		return float64(t), true
	}
	// Wide integers arrive as *big.Int from the DuckDB driver; fmt handles them
	// and the parse below recovers the value without importing math/big here.
	var f float64
	if _, err := fmt.Sscanf(fmt.Sprint(v), "%g", &f); err == nil {
		return f, true
	}
	return 0, false
}

func detailOf(err error, ctx string) string {
	if err == nil {
		return ""
	}
	return err.Error() + " — " + trunc(ctx)
}

func trunc(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if len(s) > 160 {
		return s[:157] + "…"
	}
	return s
}
