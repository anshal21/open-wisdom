// Scoring categories. Each is reported separately because they fail for
// different reasons and a single blended number would hide which.
const (
	CatStructured  = "structured output"
	CatExecutable  = "executable SQL"
	CatGroundTruth = "ground truth"
	CatIndependent = "independent derivation"
)

var categories = []string{CatStructured, CatExecutable, CatGroundTruth, CatIndependent}

