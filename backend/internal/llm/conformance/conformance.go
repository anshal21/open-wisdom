// Truth is a figure computed independently of the model, against the generated
// fixture warehouse.
//
// These are hardcoded rather than computed at runtime by a reference query on
// purpose. A runtime reference would share the harness's assumptions with the
// thing it is checking — if both reference and provider mis-handle, say, the
// timezone, they would agree and the case would pass. A frozen number cannot
// collude. The Query field records how each was derived so a reader can
// re-check it by hand.
type Truth struct {
	Value float64
	// Tolerance is relative. 1e-6 is floating-point noise on a SUM of DOUBLEs;
	// anything larger would let a genuinely different population pass.
	Tolerance float64
	Query     string
}

// Case is one question put to the provider.
type Case struct {
	Name     string
	Question string
	// Truth is set only where the question has exactly one defensible reading.
	// A question with two honest answers cannot score a provider on
	// correctness — it can only score it on obedience, which is not the same
	// thing and is not what this product wants.
	Truth *Truth
}

// Cases are fixed. Adding one changes every published score, so they are
// versioned with the suite rather than generated.
//
// # Where the ground truth comes from
//
// Every figure below is a named constant from internal/fixture, derived from
// the synthetic warehouse generated by internal/fixture/gen and committed to
// this repository as CSV. Two consequences worth stating:
//
//   - The truths are checkable. internal/fixture/truth.go carries the SQL that
//     produced each one, and TestGroundTruth re-executes all of them against the
