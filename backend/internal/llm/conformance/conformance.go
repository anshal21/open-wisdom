var (
	reLineComment  = regexp.MustCompile(`--[^\n]*`)
	reBlockComment = regexp.MustCompile(`(?s)/\*.*?\*/`)
	reAlias        = regexp.MustCompile(`(?i)\s+as\s+[a-z_][\w]*`)
	reSpace        = regexp.MustCompile(`\s+`)
	reFromJoin     = regexp.MustCompile(`(?i)\b(?:from|join)\s+([a-z_][\w.]*)`)
)

// normalizeSQL strips everything that can differ without the derivation being
// any different: comments, aliases, quoting, keyword casing, whitespace,
// trailing punctuation.
//
// What survives is the actual route: which tables, which joins, which
// expressions, which predicates.
func normalizeSQL(s string) string {
	s = reBlockComment.ReplaceAllString(s, " ")
	s = reLineComment.ReplaceAllString(s, " ")
	s = strings.ToLower(s)
	s = strings.NewReplacer(`"`, "", "`", "", "\n", " ", "\t", " ").Replace(s)
	s = reAlias.ReplaceAllString(s, " ")
	s = reSpace.ReplaceAllString(s, " ")
	return strings.TrimRight(strings.TrimSpace(s), "; ")
}

// materiallyDifferent decides whether the independent derivation is genuinely a
// second route or merely a copy of the first.
//
// The definition is deliberately narrow: two statements are the SAME only when
// they are identical after cosmetic normalisation. That is the one case where
// "the two derivations agreed" carries no information whatsoever — a query
// cannot disagree with itself, so the check that produces the `verified` seal
// would be answering a question nobody asked.
//
// It is tempting to demand more: different tables, a different join path. That
// would be wrong as a pass/fail, because crossSystem explicitly instructs the
// model to write the single available path when the schema offers only one —
// and for `SELECT count(*) FROM users` there is honestly only one. Grading that
// as failure would punish a provider for being truthful about the schema.
//
// So structural distance is measured and reported instead (see divergence), and
// only the copy is graded.
func materiallyDifferent(primary, alt string) bool {
	return normalizeSQL(primary) != normalizeSQL(alt)
}

// divergence quantifies how different the two routes are, for the report.
func divergence(name, primary, alt string) CaseDivergence {
	pa, pb := tokenSet(primary), tokenSet(alt)
	inter := 0
	for t := range pa {
		if _, ok := pb[t]; ok {
			inter++
		}
	}
	union := len(pa) + len(pb) - inter
	jaccard := 0.0
	if union > 0 {
		jaccard = 1 - float64(inter)/float64(union)
	}
	return CaseDivergence{
		Case:            name,
		TokenDistance:   jaccard,
		DifferentTables: !sameStrings(tables(primary), tables(alt)),
	}
}

func tokenSet(s string) map[string]struct{} {
	out := map[string]struct{}{}
	for _, t := range strings.Fields(normalizeSQL(s)) {
		out[strings.Trim(t, "(),")] = struct{}{}
	}
	return out
}

func tables(s string) []string {
	var out []string
	for _, m := range reFromJoin.FindAllStringSubmatch(normalizeSQL(s), -1) {
		out = append(out, m[1])
	}
	sort.Strings(out)
	return out
}

func sameStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

