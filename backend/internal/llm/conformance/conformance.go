// Assertion is one graded check.
type Assertion struct {
	Case     string
	Category string
	Name     string
	Pass     bool
	Detail   string
}

// Report is the scored outcome, formatted for pasting into a pull request.
type Report struct {
	Provider   string
	Assertions []Assertion
	// Divergence records, per case, how structurally different the independent
	// derivation was from the primary. Reported, never graded — see
	// materiallyDifferent for why.
	Divergence []CaseDivergence
	CostUSD    float64
	Calls      int
	Elapsed    time.Duration
	// Setup is a fatal environment problem: not the provider's fault and not
	// scored.
	Setup error
}

// CaseDivergence is the informational independence metric for one case.
type CaseDivergence struct {
	Case            string
	TokenDistance   float64
	DifferentTables bool
}

func (r *Report) add(c Case, category, name string, pass bool, detail string) {
	r.Assertions = append(r.Assertions, Assertion{
		Case: c.Name, Category: category, Name: name, Pass: pass, Detail: detail,
	})
}

// Score returns passed and total for a category, or overall when category is "".
func (r *Report) Score(category string) (passed, total int) {
	for _, a := range r.Assertions {
		if category != "" && a.Category != category {
			continue
		}
		total++
		if a.Pass {
			passed++
		}
	}
	return passed, total
}

// Failures lists everything that did not pass, for the detail section.
func (r *Report) Failures() []Assertion {
	var out []Assertion
	for _, a := range r.Assertions {
		if !a.Pass {
			out = append(out, a)
		}
	}
	return out
}

func pct(passed, total int) float64 {
	if total == 0 {
		return 0
	}
	return float64(passed) / float64(total) * 100
}

// String renders the markdown a contributor pastes into their PR.
func (r *Report) String() string {
	var b strings.Builder
	fmt.Fprintf(&b, "### Provider conformance — `%s`\n\n", r.Provider)
	if r.Setup != nil {
		fmt.Fprintf(&b, "**Suite did not run:** %v\n", r.Setup)
		return b.String()
	}

	fmt.Fprintf(&b, "| Category | Passed | Total | Rate |\n|---|---:|---:|---:|\n")
	for _, c := range categories {
		p, t := r.Score(c)
		if t == 0 {
			continue
		}
		fmt.Fprintf(&b, "| %s | %d | %d | %.0f%% |\n", c, p, t, pct(p, t))
	}
	p, t := r.Score("")
	fmt.Fprintf(&b, "| **overall** | **%d** | **%d** | **%.0f%%** |\n\n", p, t, pct(p, t))

	// Independence is reported, not graded beyond the copy check.
	if len(r.Divergence) > 0 {
		var sum float64
		diffTables := 0
		for _, d := range r.Divergence {
			sum += d.TokenDistance
			if d.DifferentTables {
				diffTables++
			}
		}
		fmt.Fprintf(&b,
			"Route divergence (informational): mean token distance %.2f; "+
				"different source tables in %d of %d cases.\n\n",
			sum/float64(len(r.Divergence)), diffTables, len(r.Divergence))
	}

	fmt.Fprintf(&b, "%d model calls", r.Calls)
	if r.CostUSD > 0 {
		fmt.Fprintf(&b, " · $%.4f", r.CostUSD)
	}
	fmt.Fprintf(&b, " · %s\n", r.Elapsed.Round(time.Millisecond))

	if f := r.Failures(); len(f) > 0 {
		fmt.Fprintf(&b, "\n<details><summary>%d failing assertions</summary>\n\n", len(f))
		for _, a := range f {
			fmt.Fprintf(&b, "- `%s` — **%s**: %s\n", a.Case, a.Name, a.Detail)
		}
		fmt.Fprintf(&b, "\n</details>\n")
	}
	return b.String()
}

